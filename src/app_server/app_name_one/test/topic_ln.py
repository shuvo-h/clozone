import spacy
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

# Load the spaCy English model
nlp = spacy.load("en_core_web_sm")

def extract_keywords_from_title(title):
    """Extracts keywords from the provided title using spaCy."""
    doc = nlp(title)
    # Extract nouns and proper nouns as keywords
    keywords = {token.text.lower() for token in doc if token.pos_ in {'NOUN', 'PROPN'}}
    return list(keywords)

def find_best_matching_titles(new_title, websites, contextual_words):
    # Extract keywords from the new title
    new_title_keywords = extract_keywords_from_title(new_title)

    # Extract titles from the websites
    titles = [site['title']['rendered'] for site in websites]

    # Combine titles and contextual words for TF-IDF processing
    combined_texts = titles + contextual_words

    # Create TF-IDF vectors
    vectorizer = TfidfVectorizer().fit_transform(combined_texts)
    vectors = vectorizer.toarray()

    # Calculate cosine similarity between titles and contextual words
    title_vectors = vectors[:len(titles)]
    keyword_vectors = vectors[len(titles):]

    # Prepare to hold the best matches
    best_matches = []
    seen_titles = set()
    seen_keywords = set()

    # For each contextual word, find the best matching title
    for keyword_idx, keyword_vector in enumerate(keyword_vectors):
        # Calculate similarities
        similarities = cosine_similarity([keyword_vector], title_vectors).flatten()

        # Get the index of the best matching title
        best_match_idx = similarities.argmax()

        # Check if the similarity is above a threshold
        if similarities[best_match_idx] > 0:
            matched_title = titles[best_match_idx]
            matched_keyword = contextual_words[keyword_idx]

            # Check if the matched title contains any of the keywords from the new title
            if any(keyword in matched_title.lower() for keyword in new_title_keywords):
                # Only add if the title and keyword have not been seen before
                if matched_title not in seen_titles and matched_keyword not in seen_keywords:
                    best_matches.append({
                        "title": matched_title,
                        "keyword": matched_keyword
                    })
                    seen_titles.add(matched_title)
                    seen_keywords.add(matched_keyword)

    return best_matches

